import { cpSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const siteRoot = resolve(import.meta.dirname, "..");
const generated = resolve(siteRoot, ".generated/directory");
const publicRoot = resolve(siteRoot, "public");

for (const relative of ["data", "schemas", "contribute", "templates"]) {
  rmSync(resolve(publicRoot, relative), { recursive: true, force: true });
}
mkdirSync(resolve(publicRoot, "data"), { recursive: true });

for (const name of ["catalog.json", "recommendations.json", "curation.json", "status.json"]) {
  const source = resolve(generated, name);
  JSON.parse(readFileSync(source, "utf8"));
  cpSync(source, resolve(publicRoot, "data", name));
}
cpSync(resolve(generated, "schemas"), resolve(publicRoot, "schemas"), { recursive: true });
cpSync(resolve(generated, "contribute"), resolve(publicRoot, "contribute"), { recursive: true });
cpSync(resolve(generated, "CONTRIBUTING.md"), resolve(publicRoot, "contribute/CONTRIBUTING.md"));
cpSync(resolve(generated, "templates"), resolve(publicRoot, "templates"), { recursive: true });
cpSync(resolve(generated, "skills"), resolve(publicRoot, "data/skills"), { recursive: true });
writeFileSync(resolve(publicRoot, ".generated-only"), "Do not edit; generated by npm run prepare-data.\n");
